#!/usr/bin/env python3
from __future__ import annotations
import csv,json,shutil,subprocess,tempfile
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
def score(p):
 r=subprocess.run(['python3',str(ROOT/'scripts/score_outputs.py'),'--input-dir',str(ROOT/'input'),'--output-dir',str(p),'--reference-dir',str(ROOT/'reference')],capture_output=True,text=True,check=True); return float(json.loads(r.stdout.splitlines()[-1])['score'])
def perfect(dst):
 dst.mkdir(parents=True, exist_ok=True)
 rr=np.load(ROOT/'reference/reference_arrays.npz'); z=np.load(ROOT/'input/climate_fixture.npz');
 np.savez(dst/'processed/preprocessed.npz',X_train=__import__('runpy').run_path(str(ROOT/'scripts/score_outputs.py')) if False else np.zeros((108,11,6,8)),Y_train=z['train_targets'],X_test=np.zeros((12,11,6,8)))
 # use oracle-consistent arrays generated by executing oracle helper
 import sys; sys.path.insert(0,str(ROOT/'scripts')); from oracle import make_X
 np.savez(dst/'processed/preprocessed.npz',X_train=make_X(z['train_forcing'],z['train_month'],z['lat']),Y_train=z['train_targets'],X_test=make_X(z['test_forcing'],z['test_month'],z['lat']))
 np.save(dst/'processed/coefficients.npy',rr['coefficients']); np.savez(dst/'processed/test_predictions.npz',predictions=rr['test_truth'])
 m={'schema_version':1,'target_units':{'tas':'K','pr':'mm/day'},'train_rows':108,'test_rows':12,'train_sha256':__import__('hashlib').sha256(z['train_targets'].tobytes()).hexdigest(),'forcing_mean':z['train_forcing'].mean(0).tolist(),'forcing_std':z['train_forcing'].std(0).tolist(),'target_mean':z['train_targets'].mean(axis=(0,2,3)).tolist(),'target_std':z['train_targets'].std(axis=(0,2,3)).tolist()}; (dst/'processed/metadata.json').write_text(json.dumps(m))
 p=rr['test_truth']; lat=z['lat']; w=np.cos(np.deg2rad(lat)); w=w/w.sum(); means=[float(np.sum(p[:,j].mean(0)*w[:,None])/8) for j in range(2)]; (dst/'summary.json').write_text(json.dumps({'global_mean':{'tas_K':float(p[:,0].mean()),'pr_mm_day':float(p[:,1].mean())},'rmse':{'tas_rmse':0.0,'pr_rmse':0.0},'energy_balance_check':{'lat_weighted_tas_K':means[0],'lat_weighted_pr_mm_day':means[1]}}))
 with (dst/'submissions/ssp245_predictions.csv').open('w',newline='') as f:
  wri=csv.writer(f); wri.writerow(['month','variable','lat','lon','prediction'])
  for m in range(12):
   for j,v in enumerate(['tas','pr']):
    for iy,la in enumerate(lat):
     for ix,lo in enumerate(z['lon']): wri.writerow([m,v,la,lo,p[m,j,iy,ix]])
def main():
 with tempfile.TemporaryDirectory() as t:
  b=Path(t); o=b/'oracle'; (o/'processed').mkdir(parents=True); (o/'submissions').mkdir(); perfect(o); assert score(o)==1.0
  e=b/'empty'; e.mkdir(); assert score(e)==0.0
  w=b/'wrong_units'; shutil.copytree(o,w); m=json.loads((w/'processed/metadata.json').read_text()); m['target_units']={'tas':'C','pr':'kg m-2 s-1'}; (w/'processed/metadata.json').write_text(json.dumps(m)); assert score(w)==0.0
  c=b/'visible_copy'; shutil.copytree(o,c); np.save(c/'processed/coefficients.npy',np.zeros((2,11,6,8))); assert score(c)<1.0
 print('adversarial checks passed')
if __name__=='__main__': main()
